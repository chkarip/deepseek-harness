/**
 * Pixel art matrix models for Byte (Robot), Kraken (Squid), Neko (Cyber Cat),
 * and Ni (Star Dragon).
 * Matrices are indexed [y][x] with color token characters:
 * '.' = transparent
 * 'B' = primary body color
 * 'D' = dark body / shadow
 * 'L' = light / highlight
 * 'E' = eye / screen color
 * 'P' = pupil / dark eye
 * 'A' = accent color (cyan / neon / gold)
 * 'C' = coffee / gear / tool
 * 'H' = heart / pink
 * 'W' = white
 */

import type { MascotSkin } from './tamagotchi-store.ts'

